function resizeRGBA(src, srcW, srcH, dstW, dstH) {
  var dst = new Uint8Array(dstW * dstH * 4);
  var xRatio = srcW / dstW;
  var yRatio = srcH / dstH;
  for (var y = 0; y < dstH; y++) {
    for (var x = 0; x < dstW; x++) {
      var srcX = Math.floor(x * xRatio);
      var srcY = Math.floor(y * yRatio);
      var srcIdx = (srcY * srcW + srcX) * 4;
      var dstIdx = (y * dstW + x) * 4;
      dst[dstIdx] = src[srcIdx];
      dst[dstIdx+1] = src[srcIdx+1];
      dst[dstIdx+2] = src[srcIdx+2];
      dst[dstIdx+3] = src[srcIdx+3];
    }
  }
  return dst;
}

function popularityQuantize(rgbaFrames, maxColors) {
  // v0.79: increased bin precision from 5-bit (>>3) to 6-bit (>>2)
  // for finer dark/light tone representation
  var bins = {};
  for (var f = 0; f < rgbaFrames.length; f++) {
    var rgba = rgbaFrames[f];
    for (var i = 0; i < rgba.length; i += 4) {
      var r = rgba[i] >> 2;
      var g = rgba[i+1] >> 2;
      var b = rgba[i+2] >> 2;
      var key = (r << 12) | (g << 6) | b;
      if (bins[key]) {
        bins[key].r += rgba[i];
        bins[key].g += rgba[i+1];
        bins[key].b += rgba[i+2];
        bins[key].n++;
      } else {
        bins[key] = { r: rgba[i], g: rgba[i+1], b: rgba[i+2], n: 1 };
      }
    }
  }
  var arr = [];
  for (var key in bins) {
    var b = bins[key];
    arr.push({ r: Math.round(b.r / b.n), g: Math.round(b.g / b.n), b: Math.round(b.b / b.n), n: b.n });
  }
  arr.sort(function(a, b) { return b.n - a.n; });
  var palette = [];
  var limit = Math.min(maxColors, arr.length);
  for (var i = 0; i < limit; i++) {
    palette.push((arr[i].r << 16) | (arr[i].g << 8) | arr[i].b);
  }
  var reqColors = 2;
  while (reqColors < palette.length) reqColors *= 2;
  while (palette.length < reqColors) palette.push(0);
  return palette;
}

function buildPaletteMap(palette) {
  // v0.79: 64^3 = 262144 entries for 6-bit precision
  var map = new Uint8Array(64*64*64);
  for (var r = 0; r < 64; r++) {
    for (var g = 0; g < 64; g++) {
      for (var b = 0; b < 64; b++) {
        var bestIdx = 0, bestDist = 999999;
        var rc = r << 2, gc = g << 2, bc = b << 2;
        for (var j = 0; j < palette.length; j++) {
          var pr = (palette[j] >> 16) & 0xff;
          var pg = (palette[j] >> 8) & 0xff;
          var pb = palette[j] & 0xff;
          var dr = rc - pr, dg = gc - pg, db = bc - pb;
          var dist = dr*dr + dg*dg + db*db;
          if (dist < bestDist) {
            bestDist = dist;
            bestIdx = j;
          }
        }
        map[(r << 12) | (g << 6) | b] = bestIdx;
      }
    }
  }
  return map;
}

function mapToPaletteFast(rgba, paletteMap) {
  var len = rgba.length / 4;
  var indexed = new Uint8Array(len);
  for (var i = 0; i < len; i++) {
    var r = rgba[i*4] >> 2;
    var g = rgba[i*4+1] >> 2;
    var b = rgba[i*4+2] >> 2;
    indexed[i] = paletteMap[(r << 12) | (g << 6) | b];
  }
  return indexed;
}
